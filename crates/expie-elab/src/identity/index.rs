//! Scoped identity allocation and indexing.

/// A unique identifier, scoped by an [invariant lifetime guard].
///
/// [invariant lifetime guard]: generativity::Guard
#[derive(
    Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, derive_more::Display, derive_more::Debug,
)]
#[display("{}", self.index)]
#[debug("{:?}", self.index)]
pub(in crate::identity) struct ScopedIndex<'id> {
    /// The index of the identifier.
    index: usize,
    /// A handle storing a unique invariant lifetime.
    gen_id: generativity::Id<'id>,
}

impl ScopedIndex<'_> {
    /// Returns `true` if this [`ScopedIndex`] is considered to be "the first
    /// one" allocated.
    #[must_use = "result of an equality check"]
    pub const fn is_initial(self) -> bool {
        // This will uphold the invariant if the index is unsigned
        // i.e. we only increment.
        let _: usize = self.index;
        self.index == 0
    }

    /// Convert `self` into an [`ErasedIndex`], stripping it of the
    /// [invariant lifetime].
    ///
    /// [invariant lifetime]: generativity::Guard
    #[must_use = "conversion to an erased index"]
    pub const fn erased(self) -> ErasedIndex {
        ErasedIndex(self.index)
    }
}

/// A [`Vec`] holding type `T`s, with indices corresponding to [`ScopedIndex`]s
/// generated by this structure.
///
/// Indexes generated here hold the same [invariant lifetime] as the structure
/// itself. The index value of
///
/// [invariant lifetime]: generativity::Guard
#[derive(Debug, Clone)]
pub(in crate::identity) struct ScopedIndexVec<'id, T> {
    /// The inner [`Vec`] holding the elements.
    ///
    /// It is **INVARIANT** that that this will only be pushed to.
    /// Indices can never decrement in value.
    inner: Vec<T>,
    /// A handle storing a unique invariant lifetime.
    gen_id: generativity::Id<'id>,
}

impl<'id, T> ScopedIndexVec<'id, T> {
    /// Create a new, empty [`ScopedIndexVec`], bound to the `gen_id`
    /// [invariant lifetime].
    ///
    /// [invariant lifetime]: generativity::Guard
    #[must_use = "newly allocated structure"]
    pub const fn new(gen_id: generativity::Id<'id>) -> Self {
        Self {
            inner: Vec::new(),
            gen_id,
        }
    }

    /// Iterate over the entries of the [`ScopedIndexVec`], returning a tuple
    /// pair of the [`ScopedIndex`] and the entry reference `&T`.
    ///
    /// [invariant lifetime]: generativity::Guard
    pub fn iter_indexed(&self) -> impl Iterator<Item = (ScopedIndex<'id>, &T)> {
        let gen_id = self.gen_id;
        self.inner
            .iter()
            .enumerate()
            .map(move |(index, value)| (ScopedIndex { index, gen_id }, value))
    }

    /// Returns the number of entries in the [`ScopedIndexVec`].
    #[must_use = "length check"]
    pub const fn len(&self) -> usize {
        self.inner.len()
    }

    /// Returns `true` if the [`ScopedIndexVec`] has no entries.
    #[must_use = "length check"]
    pub const fn is_empty(&self) -> bool {
        self.inner.is_empty()
    }

    /// Push a new entry, returning its corresponding [`ScopedIndex`].
    ///
    /// The index will hold the same [invariant lifetime] as the
    /// structure itself and uniquely indetifies this entry for the duration of
    /// said lifetime.
    ///
    /// [invariant lifetime]: generativity::Guard
    #[must_use = "newly allocated index, you probably want to keep this"]
    pub fn push(&mut self, value: T) -> ScopedIndex<'id> {
        let gen_id = self.gen_id;
        let index = self.inner.len();
        self.inner.push(value);
        ScopedIndex { index, gen_id }
    }

    /// Returns a reference to the entry at `id`.
    ///
    /// # Panics
    ///
    /// If the [`ScopedIndex`] was forged (i.e. we are unable to find the
    /// corresponding entry for this index, e.g. if it was not generated
    /// by [`ScopedIndexVec::push`] for this vector), this function will panic.
    #[must_use = "getter"]
    pub fn get(&self, id: ScopedIndex<'id>) -> &T {
        let raw_index = id.erased().raw_value();
        self.inner.get(raw_index).expect("scoped index was forged")
    }

    /// Returns a mutable reference to the entry at `id`.
    ///
    /// # Panics
    ///
    /// If the [`ScopedIndex`] was forged (i.e. we are unable to find the
    /// corresponding entry for this index, e.g. if it was not generated
    /// by [`ScopedIndexVec::push`] for this vector), this function will panic.
    #[must_use = "getter"]
    pub fn get_mut(&mut self, id: ScopedIndex<'id>) -> &mut T {
        let raw_index = id.erased().raw_value();
        self.inner
            .get_mut(raw_index)
            .expect("scoped index was forged")
    }
}

/// A [`ScopedIndex`] that has had its [invariant lifetime] erased.
///
/// This allows the index to be used outside the bounds of the lifetime guard.
/// This also means that it is no longer possible to guarantee that the index
/// accurately represents the [original entry] it referenced.
///
/// [invariant lifetime]: generativity::Guard
/// [original entry]: ScopedIndexVec::push
#[derive(derive_more::Debug, derive_more::Display, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[display("index:{}", _0)]
#[debug("{:?}", _0)]
pub(in crate::identity) struct ErasedIndex(
    /// The actual raw index value.
    usize,
);

impl ErasedIndex {
    /// Returns the actual underlying index of the [`ErasedIndex`].
    #[must_use = "getter"]
    pub const fn raw_value(self) -> usize {
        let Self(raw_index) = self;
        raw_index
    }
}
